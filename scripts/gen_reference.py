#!/usr/bin/env python3
"""Generate the reference pages of the docs from the code and the committed results.

Nothing here is written by hand. Run it after changing the CLI, the HTTP API, the fault
catalog, docs/claims.json or benchmarks/results:

    python scripts/gen_reference.py           # write the files
    python scripts/gen_reference.py --check   # exit 1 if a generated file is out of date

Written files (English, plus a short Portuguese wrapper for each full page):

- docs/reference/cli.md, cli.pt.md                 from ``aeon.cli.main.build_parser()``
- docs/reference/http-api.md, http-api.pt.md       from ``create_app().openapi()`` (needs fastapi)
- docs/reference/openapi.json                      the same OpenAPI document
- docs/claims.md, claims.pt.md                     from docs/claims.json
- blocks between ``<!-- BEGIN GENERATED: name -->`` and ``<!-- END GENERATED: name -->`` in
  docs/concepts/faults(.pt).md, docs/evidence/benchmarks(.pt).md and benchmarks/README.md

The standard library is enough, except for the HTTP page, which needs the ``runtime`` extra.
"""

