class Writer:
    def __init__(self, check: bool) -> None:
        self.check = check
        self.stale: list[Path] = []
        self.written: list[Path] = []

    def put(self, path: Path, text: str) -> None:
        if not text.endswith("\n"):
            text += "\n"
        current = path.read_text("utf-8") if path.is_file() else None
        if current != text:
            self.stale.append(path)
            if not self.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, "utf-8")
        self.written.append(path)

    def block(self, path: Path, name: str, content: str) -> None:
        text = path.read_text("utf-8")
        begin, end = f"<!-- BEGIN GENERATED: {name} -->", f"<!-- END GENERATED: {name} -->"
        pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
        if not pattern.search(text):
            raise SystemExit(f"gen_reference: {path} has no '{begin}' marker")
        new = pattern.sub(lambda _m: f"{begin}\n{content.rstrip()}\n{end}", text)
        if new != text:
            self.stale.append(path)
            if not self.check:
                path.write_text(new, "utf-8")


def suffix(lang: str) -> str:
    return ".md" if lang == "en" else ".pt.md"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")
    args = ap.parse_args()
    w = Writer(args.check)

    for lang in LANGS:
        w.put(DOCS / "reference" / f"cli{suffix(lang)}", cli_markdown(lang))
        w.put(DOCS / f"claims{suffix(lang)}", claims_markdown(lang))
        w.block(DOCS / "concepts" / f"faults{suffix(lang)}", "faults", faults_block(lang))
        for name, content in bench_blocks(lang).items():
            w.block(DOCS / "evidence" / f"benchmarks{suffix(lang)}", name, content)

    w.block(ROOT / "benchmarks" / "README.md", "unfavourable", unfavourable_block())

    try:
        spec = build_openapi()
    except ImportError as exc:
        print(f"gen_reference: skipping the HTTP page ({exc}); install aeon-core[runtime]")
    else:
        w.put(DOCS / "reference" / "openapi.json", json.dumps(spec, indent=2, ensure_ascii=False))
        for lang in LANGS:
            w.put(DOCS / "reference" / f"http-api{suffix(lang)}", http_markdown(lang, spec))

    if args.check:
        for p in w.stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if w.stale else 0
    for p in w.stale:
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(w.stale)} file(s) changed, {len(w.written)} generated files checked")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
