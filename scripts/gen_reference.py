def _subparsers(p: argparse.ArgumentParser) -> argparse._SubParsersAction[Any] | None:
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            return a
    return None


def _walk(p: argparse.ArgumentParser, path: list[str], helps: dict[str, str]) -> Iterable[Any]:
    yield path, p, helps.get(" ".join(path), p.description or "")
    sub = _subparsers(p)
    if sub is None:
        return
    child_help = {ca.dest: (ca.help or "") for ca in sub._choices_actions}
    for name, child in sub.choices.items():
        child_path = [*path, name]
        yield from _walk(child, child_path, {" ".join(child_path): child_help.get(name, "")})


def _option_rows(p: argparse.ArgumentParser) -> list[list[str]]:
    rows = []
    for a in p._actions:
        if isinstance(a, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        name = ", ".join(f"`{o}`" for o in a.option_strings) if a.option_strings else f"`{a.dest}`"
        if a.choices:
            name += " " + "{" + ",".join(map(str, a.choices)) + "}"
        default = a.default
        shown = "" if default in (None, False, argparse.SUPPRESS, []) else f"`{default}`"
        rows.append([name, shown, a.help or ""])
    return rows


def cli_markdown(lang: str) -> str:
    os.environ["COLUMNS"] = "100"
    from aeon.cli.main import build_parser

    parser = build_parser()
    intro = {
        "en": [
            "# CLI reference",
            "",
            "The `aeon` command uses only the standard library. Every command that prints data "
            "accepts `--json`. Expected failures print a message and a fix hint and exit "
            "non-zero; they never print a stack trace. Exit codes: `0` ok, `1` failure "
            "(including a failed `--strict` campaign or a broken audit chain), `2` usage error.",
        ],
        "pt": [
            "# Referência da CLI",
            "",
            "O comando `aeon` usa só a biblioteca padrão. Todo comando que imprime dados aceita "
            "`--json`. Falhas esperadas mostram uma mensagem e uma dica de correção e saem com "
            "código diferente de zero, sem stack trace. Códigos de saída: `0` ok, `1` falha "
            "(inclui campanha reprovada com `--strict` e cadeia de auditoria quebrada), "
            "`2` erro de uso. Os textos de ajuda abaixo vêm do código e estão em inglês.",
        ],
    }[lang]
    heads = {
        "en": ("Option", "Default", "Description"),
        "pt": ("Opção", "Padrão", "Descrição"),
    }[lang]
    out = [intro[0], "", banner(lang, "`aeon.cli.main.build_parser()`"), *intro[1:], ""]
    for path, p, help_text in _walk(parser, ["aeon"], {}):
        if path == ["aeon"]:
            out += ["## `aeon`", "", "```text", p.format_usage().strip(), "```", ""]
            out.append(help_text.strip() + "\n" if help_text else "")
        else:
            sub = _subparsers(p)
            level = "##" if len(path) == 2 else "###"
            out += [f"{level} `{' '.join(path)}`", ""]
            if help_text:
                out += [help_text.strip(), ""]
            out += ["```text", p.format_usage().strip(), "```", ""]
            if sub is not None and not [a for a in _option_rows(p)]:
                continue
        rows = _option_rows(p)
        if rows:
            out += [table(heads, rows)]
    return "\n".join(out).rstrip() + "\n"


