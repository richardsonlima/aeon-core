def banner(lang: str, source: str) -> str:
    body = WORDS["banner_body"][lang].format(source=source)
    return f'!!! info "{WORDS["banner_title"][lang]}"\n    {body}\n'


def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def table(head: Iterable[str], rows: Iterable[Iterable[object]]) -> str:
    head = list(head)
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


