def _schema_fields(spec: Mapping[str, Any], schema: Mapping[str, Any]) -> str:
    ref = schema.get("$ref")
    if ref:
        schema = spec["components"]["schemas"][ref.rsplit("/", 1)[-1]]
    if "anyOf" in schema:
        for option in schema["anyOf"]:
            if "$ref" in option:
                return _schema_fields(spec, option)
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    parts = []
    for name, prop in props.items():
        kind = prop.get("type") or ("/".join(t.get("type", "?") for t in prop.get("anyOf", [])))
        parts.append(f"`{name}`{'' if name in required else '?'}: {kind or 'any'}")
    return ", ".join(parts)


def build_openapi() -> dict[str, Any]:
    os.environ["AEON_AUDIT"] = "off"
    for var in ("AEON_CONFIG", "AEON_RUNTIME_TOKEN", "AEON_AXIOMS", "AEON_MODE"):
        os.environ.pop(var, None)
    from aeon.config import Config
    from aeon.runtime.app import create_app

    cwd = Path.cwd()
    with tempfile.TemporaryDirectory() as td:
        os.chdir(td)
        try:
            app = create_app(config=Config(audit="off", root=Path(td)), token="docs-throwaway")  # noqa: S106
            doc: dict[str, Any] = app.openapi()
        finally:
            os.chdir(cwd)
    return doc


def http_markdown(lang: str, spec: Mapping[str, Any]) -> str:
    from aeon.runtime.app import STREAM_PATH

    heads = {
        "en": ("Method", "Path", "What it does", "Auth", "Request body"),
        "pt": ("Método", "Caminho", "O que faz", "Autenticação", "Corpo da requisição"),
    }[lang]
    rows, missing = [], []
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            key = (method.upper(), path)
            text = ROUTE_DOCS.get(key)
            if text is None:
                missing.append(key)
                text = op.get("summary", "")
            if not path.startswith("/v1"):
                auth = "none"
            elif path == STREAM_PATH:
                auth = "Bearer, or `?token=` (EventSource cannot set headers)"
            else:
                auth = "Bearer"
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {})
            fields = _schema_fields(spec, body.get("schema", {})) if body else ""
            rows.append([method.upper(), f"`{path}`", text, auth, fields])
    if missing:
        raise SystemExit(
            "gen_reference: add a description to ROUTE_DOCS for: "
            + ", ".join(f"{m} {p}" for m, p in missing)
        )
    intro = {
        "en": [
            "# HTTP API reference",
            "",
            "The local runtime (`aeon runtime start`, alias `aeon serve`) serves this API. It "
            "decides and records; it never executes a tool. Every `/v1` route needs "
            "`Authorization: Bearer <token>`. The machine-readable document is "
            "[openapi.json](openapi.json). A `?` after a field name means optional.",
        ],
        "pt": [
            "# Referência da API HTTP",
            "",
            "O runtime local (`aeon runtime start`, alias `aeon serve`) serve esta API. Ele "
            "decide e registra; nunca executa uma ferramenta. Toda rota `/v1` exige "
            "`Authorization: Bearer <token>`. O documento legível por máquina é o "
            "[openapi.json](openapi.json). Um `?` depois do nome do campo significa opcional. "
            "As descrições abaixo vêm do código e estão em inglês.",
        ],
    }[lang]
    return (
        intro[0]
        + "\n\n"
        + banner(lang, "`create_app().openapi()`")
        + "\n"
        + "\n".join(intro[1:])
        + "\n\n"
        + table(heads, rows)
    )


