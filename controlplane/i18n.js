const KEY = "aeon.lang";
let lang = "en";

export function detectLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "pt") return saved;
  } catch (_e) { /* storage may be blocked */ }
  const nav = (navigator.language || "en").toLowerCase();
  return nav.startsWith("pt") ? "pt" : "en";
}

export function getLang() { return lang; }

export function setLang(next) {
  lang = next === "pt" ? "pt" : "en";
  try { localStorage.setItem(KEY, lang); } catch (_e) { /* ignore */ }
  document.documentElement.setAttribute("lang", lang === "pt" ? "pt-BR" : "en");
}

export function initLang() { setLang(detectLang()); }

export function t(key) {
  const dict = lang === "pt" ? PT : EN;
  return dict[key] ?? EN[key] ?? key;
}

export function applyStatic(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-label]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nLabel));
  }
}
